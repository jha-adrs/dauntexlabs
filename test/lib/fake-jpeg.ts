/** Structurally valid JPEG of exactly n bytes (n ≥ 26): SOI + JFIF APP0 + SOS + filler + EOI. */
export function fakeJpeg(n: number): Uint8Array {
  if (n < 26) throw new Error('fakeJpeg needs n >= 26')
  const out = new Uint8Array(n)
  out.set([0xff, 0xd8])
  out.set([0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00], 2)
  out.set([0xff, 0xda, 0x00, 0x02], 20)
  out.fill(0x55, 24, n - 2)
  out.set([0xff, 0xd9], n - 2)
  return out
}
